using System.Text;

namespace XfsTestGen;

/// <summary>Emits the C# xunit tests and the P/Invoke declarations for the generated native exports.</summary>
public static class CsWriter
{
    public static string NativeMethods(string testNamespace, IEnumerable<StructModel> structs)
    {
        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated by XfsTestGen. Do not edit.>");
        sb.AppendLine("using System.Runtime.InteropServices;");
        sb.AppendLine();
        sb.AppendLine($"namespace {testNamespace};");
        sb.AppendLine();
        sb.AppendLine("/// <summary>Exports of tests/DenoXfsTestNative (C++ built from the real XFS headers).</summary>");
        sb.AppendLine("internal static class NativeMethods");
        sb.AppendLine("{");
        sb.AppendLine("    private const string Dll = \"DenoXfsTestNative.dll\";");
        foreach (var m in structs)
        {
            var f = m.Planned.Name;
            sb.AppendLine();
            sb.AppendLine($"    [DllImport(Dll, CallingConvention = CallingConvention.Cdecl)] public static extern IntPtr Native_Create_{f}(int sc);");
            sb.AppendLine($"    [DllImport(Dll, CallingConvention = CallingConvention.Cdecl)] public static extern void Native_Free_{f}(IntPtr p);");
            sb.AppendLine($"    [DllImport(Dll, CallingConvention = CallingConvention.Cdecl)] public static extern int Native_Verify_{f}(IntPtr p, int sc);");
            sb.AppendLine($"    [DllImport(Dll, CallingConvention = CallingConvention.Cdecl)] public static extern int Native_Layout_{f}([MarshalAs(UnmanagedType.LPStr)] string? field);");
        }

        sb.AppendLine("}");
        return sb.ToString();
    }

    public static string Tests(string testNamespace, IEnumerable<string> usings, StructModel m)
    {
        var f = m.Planned.Name;
        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated by XfsTestGen. Do not edit.>");
        sb.AppendLine("using System.Runtime.InteropServices;");
        sb.AppendLine("using DenoXfs.Interop.Convert;");
        foreach (var u in usings)
            sb.AppendLine($"using {u};");
        sb.AppendLine();
        sb.AppendLine($"namespace {testNamespace};");
        sb.AppendLine();
        sb.AppendLine($"/// <summary>{m.Planned.TypedefName}: {m.Planned.Reason}</summary>");
        sb.AppendLine($"public class {f}Tests");
        sb.AppendLine("{");

        // layout
        sb.AppendLine("    [Fact]");
        sb.AppendLine("    public void Layout_matches_cpp()");
        sb.AppendLine("    {");
        sb.AppendLine($"        Assert.Equal(NativeMethods.Native_Layout_{f}(null), Marshal.SizeOf<{f}>());");
        foreach (var field in m.Fields)
            sb.AppendLine($"        Assert.Equal(NativeMethods.Native_Layout_{f}(\"{field.CName}\"), (int)Marshal.OffsetOf<{f}>(\"{field.Private}\"));");
        sb.AppendLine("    }");
        sb.AppendLine();

        // native -> managed
        sb.AppendLine("    [Theory]");
        sb.AppendLine("    [InlineData(0)]");
        sb.AppendLine("    [InlineData(1)]");
        sb.AppendLine("    public void Native_to_managed(int sc)");
        sb.AppendLine("    {");
        sb.AppendLine($"        var p = NativeMethods.Native_Create_{f}(sc);");
        sb.AppendLine("        try");
        sb.AppendLine("        {");
        sb.AppendLine($"            Check(IntPtrConvert.ToStruct<{f}>(p), sc);");
        sb.AppendLine("        }");
        sb.AppendLine("        finally");
        sb.AppendLine("        {");
        sb.AppendLine($"            NativeMethods.Native_Free_{f}(p);");
        sb.AppendLine("        }");
        sb.AppendLine("    }");
        sb.AppendLine();

        // managed -> native
        sb.AppendLine("    [Theory]");
        sb.AppendLine("    [InlineData(0)]");
        sb.AppendLine("    [InlineData(1)]");
        sb.AppendLine("    public void Managed_to_native(int sc)");
        sb.AppendLine("    {");
        sb.AppendLine($"        var p = Marshal.AllocHGlobal(Marshal.SizeOf<{f}>());");
        sb.AppendLine("        try");
        sb.AppendLine("        {");
        sb.AppendLine("            Marshal.StructureToPtr(Build(sc), p, false);");
        sb.AppendLine($"            Assert.Equal(0, NativeMethods.Native_Verify_{f}(p, sc));");
        sb.AppendLine("        }");
        sb.AppendLine("        finally");
        sb.AppendLine("        {");
        sb.AppendLine("            Marshal.FreeHGlobal(p);");
        sb.AppendLine("        }");
        sb.AppendLine("    }");
        sb.AppendLine();

        AppendBuild(sb, m);
        sb.AppendLine();
        AppendCheck(sb, m);
        sb.AppendLine("}");
        return sb.ToString();
    }

    private static void AppendBuild(StringBuilder sb, StructModel m)
    {
        var f = m.Planned.Name;
        sb.AppendLine($"    public static {f} Build(int sc)");
        sb.AppendLine("    {");
        sb.AppendLine($"        var s = new {f}();");
        foreach (var field in m.Fields.Where(x => x.Kind is Kind.NumberArray or Kind.OpaqueArray))
            sb.AppendLine($"        s.{field.Property} = new {field.CsType}[{field.ArraySize}];");

        sb.AppendLine("        if (sc == 1) return s;");
        foreach (var field in m.Fields)
        {
            var p = $"s.{field.Property}";
            switch (field.Kind)
            {
                case Kind.Number when !field.IsConsumedLength:
                    sb.AppendLine($"        {p} = ({field.CsType}){field.Index + 1};");
                    break;
                case Kind.Bool:
                    sb.AppendLine($"        {p} = true;");
                    break;
                case Kind.NumberArray:
                    sb.AppendLine($"        for (var j = 0; j < {field.ArraySize}; j++) {p}[j] = ({field.CsType})((({field.Index} * 7 + j) % 250) + 1);");
                    break;
                case Kind.String:
                    sb.AppendLine($"        {p} = \"s{field.Index}\";");
                    break;
                case Kind.WString:
                    sb.AppendLine($"        {p} = \"w{field.Index}\";");
                    break;
                case Kind.BytesTerminated:
                    sb.AppendLine($"        {p} = new byte[] {{ 1, 2, 3 }};");
                    break;
                case Kind.BytesCounted:
                    sb.AppendLine($"        {p} = new byte[] {{ 1, 2, 0, 4, 0, 0, 7 }};");
                    break;
                case Kind.PrimitiveList:
                    sb.AppendLine($"        {p} = new {field.CsType}[] {{ {string.Join(", ", field.ListItems)} }};");
                    break;
                case Kind.EnumList:
                    sb.AppendLine($"        {p} = new {field.CsType}[] {{ ({field.CsType})1, ({field.CsType})2 }};");
                    break;
                case Kind.Nested:
                    sb.AppendLine($"        {p} = {field.Target}Tests.Build(0);");
                    break;
                case Kind.StructList:
                    sb.AppendLine($"        {p} = new {field.Target}?[] {{ {field.Target}Tests.Build(0), {field.Target}Tests.Build(0) }};");
                    break;
            }
        }

        sb.AppendLine("        return s;");
        sb.AppendLine("    }");
    }

    private static void AppendCheck(StringBuilder sb, StructModel m)
    {
        var f = m.Planned.Name;
        sb.AppendLine($"    public static void Check({f} s, int sc)");
        sb.AppendLine("    {");
        foreach (var field in m.Fields.Where(x => x.Kind is Kind.NumberArray or Kind.OpaqueArray))
            sb.AppendLine($"        Assert.Equal({field.ArraySize}, s.{field.Property}.Length);");

        sb.AppendLine("        if (sc == 1)");
        sb.AppendLine("        {");
        foreach (var field in m.Fields)
        {
            var p = $"s.{field.Property}";
            switch (field.Kind)
            {
                case Kind.Number:
                    sb.AppendLine($"            Assert.Equal(default({field.CsType}), {p});");
                    break;
                case Kind.Bool:
                    sb.AppendLine($"            Assert.False({p});");
                    break;
                case Kind.NumberArray:
                case Kind.OpaqueArray:
                    sb.AppendLine($"            Assert.All({p}, x => Assert.Equal(default({field.CsType}), x));");
                    break;
                case Kind.String:
                case Kind.WString:
                case Kind.BytesTerminated:
                case Kind.BytesCounted:
                case Kind.PrimitiveList:
                case Kind.EnumList:
                case Kind.Nested:
                case Kind.StructList:
                    sb.AppendLine($"            Assert.Null({p});");
                    break;
            }
        }

        sb.AppendLine("            return;");
        sb.AppendLine("        }");
        sb.AppendLine();

        foreach (var field in m.Fields)
        {
            var p = $"s.{field.Property}";
            switch (field.Kind)
            {
                case Kind.Number:
                    var expected = field.IsConsumedLength ? "7" : (field.Index + 1).ToString();
                    sb.AppendLine($"        Assert.Equal(({field.CsType}){expected}, {p});");
                    break;
                case Kind.Bool:
                    sb.AppendLine($"        Assert.True({p});");
                    break;
                case Kind.NumberArray:
                    sb.AppendLine($"        for (var j = 0; j < {field.ArraySize}; j++) Assert.Equal(({field.CsType})((({field.Index} * 7 + j) % 250) + 1), {p}[j]);");
                    break;
                case Kind.String:
                    sb.AppendLine($"        Assert.Equal(\"s{field.Index}\", {p});");
                    break;
                case Kind.WString:
                    sb.AppendLine($"        Assert.Equal(\"w{field.Index}\", {p});");
                    break;
                case Kind.BytesTerminated:
                    sb.AppendLine($"        Assert.Equal(new byte[] {{ 1, 2, 3 }}, {p});");
                    break;
                case Kind.BytesCounted:
                    sb.AppendLine($"        Assert.Equal(new byte[] {{ 1, 2, 0, 4, 0, 0, 7 }}, {p});");
                    break;
                case Kind.PrimitiveList:
                    sb.AppendLine($"        Assert.Equal(new {field.CsType}[] {{ {string.Join(", ", field.ListItems)} }}, {p});");
                    break;
                case Kind.EnumList:
                    sb.AppendLine($"        Assert.Equal(new {field.CsType}[] {{ ({field.CsType})1, ({field.CsType})2 }}, {p});");
                    break;
                case Kind.Nested:
                    sb.AppendLine($"        Assert.NotNull({p});");
                    sb.AppendLine($"        {field.Target}Tests.Check({p}!.Value, 0);");
                    break;
                case Kind.StructList:
                    sb.AppendLine($"        Assert.NotNull({p});");
                    sb.AppendLine($"        Assert.Equal(2, {p}!.Length);");
                    sb.AppendLine($"        foreach (var item in {p}) {field.Target}Tests.Check(item!.Value, 0);");
                    break;
            }
        }

        sb.AppendLine("    }");
    }
}
